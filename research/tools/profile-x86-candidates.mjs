#!/usr/bin/env node

/**
 * Profile the x86-looking compiled-object candidates in a DXL image.
 *
 * The profiler uses GNU objdump only as a bounded byte decoder.  It records
 * instruction and relative-transfer summaries, but it does not assign a
 * symbol, entry point, relocation, source module, or Lisp meaning to any
 * candidate.  Linear decoding can interpret embedded data as instructions;
 * the recursive view is retained as a separate conservative comparison.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import {
  parseCompiledObjectTable,
  parseIndexTable,
  sha256,
} from './index-allegro-image.mjs';

const DEFAULT_OBJDUMP = 'objdump';

function assertInteger(value, label, minimum = 0) {
  if (!Number.isInteger(value) || value < minimum) {
    throw new RangeError(`${label} must be an integer >= ${minimum}`);
  }
  return value;
}

function signed8(value) {
  return value & 0x80 ? value - 0x100 : value;
}

function signed32(bytes, offset = 0) {
  const value = (bytes[offset]
    | (bytes[offset + 1] << 8)
    | (bytes[offset + 2] << 16)
    | (bytes[offset + 3] << 24));
  return value;
}

function firstMnemonic(asm) {
  return asm.trim().split(/\s+/, 1)[0]?.toLowerCase() ?? '';
}

function isInvalidInstruction(instruction) {
  return instruction.asm.includes('(bad)')
    || instruction.asm.startsWith('.byte')
    || instruction.asm.startsWith('.word')
    || instruction.asm.startsWith('.long');
}

/**
 * Parse the tab-separated instruction rows emitted by GNU objdump.
 *
 * This accepts the bounded output of `objdump -b binary -m i386 -D` and keeps
 * the raw assembly text only in memory.  Reports generated by the CLI do not
 * retain the disassembly itself.
 */
export function parseObjdumpInstructions(text) {
  if (typeof text !== 'string') throw new TypeError('objdump text must be a string');
  const instructions = [];
  for (const line of text.split('\n')) {
    const columns = line.split('\t');
    if (columns.length < 3) continue;
    const addressMatch = /^\s*([0-9a-f]+):$/.exec(columns[0]);
    if (!addressMatch) continue;
    const byteTokens = columns[1].match(/[0-9a-f]{2}/gi) ?? [];
    if (byteTokens.length === 0) continue;
    const bytes = Buffer.from(byteTokens.map((token) => Number.parseInt(token, 16)));
    instructions.push({
      offset: Number.parseInt(addressMatch[1], 16),
      length: bytes.length,
      bytes,
      asm: columns.slice(2).join('\t').trim(),
    });
  }
  return instructions;
}

function relativeTransfer(instruction) {
  const { bytes, offset, length } = instruction;
  const opcode = bytes[0];
  if (opcode === 0xe8 && length === 5) {
    return { kind: 'call', conditional: false, target: offset + length + signed32(bytes, 1) };
  }
  if (opcode === 0xe9 && length === 5) {
    return { kind: 'jump', conditional: false, target: offset + length + signed32(bytes, 1) };
  }
  if (opcode === 0xeb && length === 2) {
    return { kind: 'jump', conditional: false, target: offset + length + signed8(bytes[1]) };
  }
  if (opcode >= 0x70 && opcode <= 0x7f && length === 2) {
    return { kind: 'conditional-jump', conditional: true, target: offset + length + signed8(bytes[1]) };
  }
  if (opcode >= 0xe0 && opcode <= 0xe3 && length === 2) {
    return { kind: 'conditional-jump', conditional: true, target: offset + length + signed8(bytes[1]) };
  }
  if (opcode === 0x0f && bytes[1] >= 0x80 && bytes[1] <= 0x8f && length === 6) {
    return {
      kind: 'conditional-jump',
      conditional: true,
      target: offset + length + signed32(bytes, 2),
    };
  }
  return null;
}

function indirectTransfer(instruction) {
  const mnemonic = firstMnemonic(instruction.asm);
  if (mnemonic !== 'call' && mnemonic !== 'jmp') return null;
  if (relativeTransfer(instruction)) return null;
  return mnemonic === 'call' ? 'call' : 'jump';
}

function isTerminal(instruction) {
  const mnemonic = firstMnemonic(instruction.asm);
  return mnemonic === 'ret'
    || mnemonic === 'retl'
    || mnemonic === 'lret'
    || mnemonic === 'iret'
    || mnemonic === 'iretd'
    || mnemonic === 'iretq'
    || mnemonic === 'ud2'
    || mnemonic === 'hlt';
}

function candidateRange(candidate) {
  const start = assertInteger(candidate.offset, 'candidate.offset');
  const rawEnd = assertInteger(candidate.rawEnd, 'candidate.rawEnd', start + 4);
  return { start, payloadStart: start + 4, end: rawEnd };
}

function contains(range, offset) {
  return offset >= range.start && offset < range.end;
}

function classifyTarget(target, range, candidateRanges, instructionStarts, instructionRanges) {
  if (contains({ start: range.payloadStart, end: range.end }, target)) {
    if (instructionStarts.has(target)) return 'origin-instruction-start';
    if (instructionRanges.some(({ start, end }) => target > start && target < end)) {
      return 'origin-instruction-interior';
    }
    return 'origin-unclassified-byte';
  }
  const other = candidateRanges.find((candidate) => (
    candidate.start !== range.start && contains(candidate, target)
  ));
  if (other) {
    return target === other.payloadStart ? 'other-candidate-payload-start' : 'other-candidate-range';
  }
  return 'outside-origin';
}

function increment(map, key, amount = 1) {
  map.set(key, (map.get(key) ?? 0) + amount);
}

function countMemoryRegister(instructions, register) {
  const pattern = new RegExp(`\\(%${register}(?:[,)])`);
  return instructions.filter(({ asm }) => pattern.test(asm)).length;
}

function summarizeCounts(map) {
  return Object.fromEntries([...map.entries()].sort(([left], [right]) => left.localeCompare(right)));
}

function transferSummary(instructions, range, candidateRanges) {
  const instructionStarts = new Set(instructions.map(({ offset }) => offset));
  const instructionRanges = instructions.map(({ offset, length }) => ({
    start: offset,
    end: offset + length,
  }));
  const targetClasses = new Map();
  const transfers = [];
  let directCallCount = 0;
  let directJumpCount = 0;
  let conditionalJumpCount = 0;
  let indirectCallCount = 0;
  let indirectJumpCount = 0;
  for (const instruction of instructions) {
    const relative = relativeTransfer(instruction);
    if (relative) {
      const targetClass = classifyTarget(
        relative.target,
        range,
        candidateRanges,
        instructionStarts,
        instructionRanges,
      );
      increment(targetClasses, targetClass);
      transfers.push({
        offset: instruction.offset,
        kind: relative.kind,
        target: relative.target,
        targetClass,
      });
      if (relative.kind === 'call') directCallCount += 1;
      else if (relative.conditional) conditionalJumpCount += 1;
      else directJumpCount += 1;
      continue;
    }
    const indirect = indirectTransfer(instruction);
    if (indirect === 'call') indirectCallCount += 1;
    if (indirect === 'jump') indirectJumpCount += 1;
  }
  return {
    directCallCount,
    directJumpCount,
    conditionalJumpCount,
    directTransferCount: directCallCount + directJumpCount + conditionalJumpCount,
    indirectCallCount,
    indirectJumpCount,
    targetClassCounts: summarizeCounts(targetClasses),
    transfers,
    instructionStarts,
    instructionRanges,
  };
}

/**
 * Follow the bounded linear instruction graph from the payload start.
 *
 * The default view stops at indirect transfers.  The optional assumed-return
 * view treats indirect calls as returning to the next linear instruction,
 * while still stopping at indirect jumps.  That is a coverage control, not a
 * recovered calling convention or a claim that every call returns.
 */
function recursiveSummary(
  instructions,
  range,
  candidateRanges,
  transfer,
  { assumeIndirectCallsReturn = false } = {},
) {
  const byOffset = new Map(instructions.map((instruction) => [instruction.offset, instruction]));
  const starts = transfer.instructionStarts;
  const instructionRanges = transfer.instructionRanges;
  const queue = [range.payloadStart];
  const visited = new Set();
  const invalidStarts = new Set();
  const unclassifiedStarts = new Set();
  const stopReasons = new Map();
  const traversedTransfers = [];
  let assumedReturnCallCount = 0;

  const enqueue = (target) => {
    if (target < range.payloadStart || target >= range.end) return;
    if (starts.has(target)) {
      queue.push(target);
      return;
    }
    if (instructionRanges.some(({ start, end }) => target > start && target < end)) {
      increment(stopReasons, 'target-inside-linear-instruction');
    } else {
      unclassifiedStarts.add(target);
      increment(stopReasons, 'target-unclassified-byte');
    }
  };

  while (queue.length) {
    const offset = queue.pop();
    if (visited.has(offset)) continue;
    const instruction = byOffset.get(offset);
    if (!instruction || offset < range.payloadStart || offset >= range.end) {
      unclassifiedStarts.add(offset);
      increment(stopReasons, 'missing-linear-instruction');
      continue;
    }
    visited.add(offset);
    if (isInvalidInstruction(instruction)) {
      invalidStarts.add(offset);
      increment(stopReasons, 'invalid-or-byte-fallback');
      continue;
    }
    const relative = relativeTransfer(instruction);
    if (relative) {
      const targetClass = classifyTarget(
        relative.target,
        range,
        candidateRanges,
        starts,
        instructionRanges,
      );
      traversedTransfers.push({
        offset: instruction.offset,
        kind: relative.kind,
        target: relative.target,
        targetClass,
      });
      if (relative.kind === 'conditional-jump') {
        enqueue(relative.target);
        enqueue(instruction.offset + instruction.length);
      } else if (relative.kind === 'jump') {
        enqueue(relative.target);
      } else {
        // Direct calls are summarized as dependencies, but their callees are
        // not recursively attributed to this candidate.
        enqueue(instruction.offset + instruction.length);
      }
      continue;
    }
    const transferKind = indirectTransfer(instruction);
    if (transferKind) {
      if (transferKind === 'call' && assumeIndirectCallsReturn) {
        assumedReturnCallCount += 1;
        increment(stopReasons, 'indirect-call-assumed-return');
        enqueue(instruction.offset + instruction.length);
      } else {
        increment(stopReasons, 'indirect-transfer');
      }
      continue;
    }
    if (isTerminal(instruction)) {
      increment(stopReasons, 'terminal-instruction');
      continue;
    }
    enqueue(instruction.offset + instruction.length);
  }

  const reachableBytes = [...visited].reduce((total, offset) => {
    const instruction = byOffset.get(offset);
    return total + (instruction?.length ?? 0);
  }, 0);
  return {
    instructionCount: visited.size,
    reachableBytes,
    coverageRatio: (range.end - range.payloadStart) === 0
      ? 0
      : reachableBytes / (range.end - range.payloadStart),
    invalidStartCount: invalidStarts.size,
    unclassifiedStartCount: unclassifiedStarts.size,
    assumedReturnCallCount,
    stopReasonCounts: summarizeCounts(stopReasons),
    transfers: traversedTransfers,
  };
}

/**
 * Summarize one bounded objdump instruction stream.
 */
export function profileInstructionStream(instructions, candidate, candidateRanges = []) {
  if (!Array.isArray(instructions)) throw new TypeError('instructions must be an array');
  const range = candidateRange(candidate);
  const bounded = instructions.filter((instruction) => (
    instruction.offset >= range.payloadStart && instruction.offset < range.end
  ));
  const transfer = transferSummary(bounded, range, candidateRanges);
  const invalidCount = bounded.filter(isInvalidInstruction).length;
  const recursive = recursiveSummary(bounded, range, candidateRanges, transfer);
  const assumedReturn = recursiveSummary(
    bounded,
    range,
    candidateRanges,
    transfer,
    { assumeIndirectCallsReturn: true },
  );
  return {
    linear: {
      instructionCount: bounded.length,
      decodedBytes: bounded.reduce((total, instruction) => total + instruction.length, 0),
      invalidCount,
      operandSignatureCounts: {
        ediMemoryInstructionCount: countMemoryRegister(bounded, 'edi'),
        esiMemoryInstructionCount: countMemoryRegister(bounded, 'esi'),
        ebpMemoryInstructionCount: countMemoryRegister(bounded, 'ebp'),
        immediateInstructionCount: bounded.filter(({ asm }) => /\$0x[0-9a-f]+/.test(asm)).length,
      },
      ...transfer,
    },
    recursive,
    assumedReturn,
  };
}

function runObjdump(imagePath, start, end, objdump = DEFAULT_OBJDUMP) {
  assertInteger(start, 'disassembly start');
  assertInteger(end, 'disassembly end', start + 1);
  const output = execFileSync(objdump, [
    '-b', 'binary',
    '-m', 'i386',
    '-D',
    '--insn-width=16',
    `--start-address=${start}`,
    `--stop-address=${end}`,
    imagePath,
  ], { encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 });
  return parseObjdumpInstructions(output);
}

function aggregateProfiles(profiles) {
  const totals = {
    candidateCount: profiles.length,
    linearInstructionCount: 0,
    linearDecodedBytes: 0,
    linearInvalidCount: 0,
    recursiveInstructionCount: 0,
    recursiveReachableBytes: 0,
    recursiveInvalidStartCount: 0,
    recursiveUnclassifiedStartCount: 0,
    assumedReturnInstructionCount: 0,
    assumedReturnReachableBytes: 0,
    assumedReturnInvalidStartCount: 0,
    assumedReturnUnclassifiedStartCount: 0,
    assumedReturnCallCount: 0,
    directCallCount: 0,
    directJumpCount: 0,
    conditionalJumpCount: 0,
    directTransferCount: 0,
    indirectCallCount: 0,
    indirectJumpCount: 0,
    targetClassCounts: new Map(),
    stopReasonCounts: new Map(),
    operandSignatureCounts: new Map(),
  };
  for (const profile of profiles) {
    const { linear, recursive, assumedReturn } = profile;
    totals.linearInstructionCount += linear.instructionCount;
    totals.linearDecodedBytes += linear.decodedBytes;
    totals.linearInvalidCount += linear.invalidCount;
    totals.recursiveInstructionCount += recursive.instructionCount;
    totals.recursiveReachableBytes += recursive.reachableBytes;
    totals.recursiveInvalidStartCount += recursive.invalidStartCount;
    totals.recursiveUnclassifiedStartCount += recursive.unclassifiedStartCount;
    totals.assumedReturnInstructionCount += assumedReturn.instructionCount;
    totals.assumedReturnReachableBytes += assumedReturn.reachableBytes;
    totals.assumedReturnInvalidStartCount += assumedReturn.invalidStartCount;
    totals.assumedReturnUnclassifiedStartCount += assumedReturn.unclassifiedStartCount;
    totals.assumedReturnCallCount += assumedReturn.assumedReturnCallCount;
    totals.directCallCount += linear.directCallCount;
    totals.directJumpCount += linear.directJumpCount;
    totals.conditionalJumpCount += linear.conditionalJumpCount;
    totals.directTransferCount += linear.directTransferCount;
    totals.indirectCallCount += linear.indirectCallCount;
    totals.indirectJumpCount += linear.indirectJumpCount;
    for (const [key, value] of Object.entries(linear.targetClassCounts)) increment(totals.targetClassCounts, key, value);
    for (const [key, value] of Object.entries(recursive.stopReasonCounts)) increment(totals.stopReasonCounts, key, value);
    for (const [key, value] of Object.entries(linear.operandSignatureCounts)) increment(totals.operandSignatureCounts, key, value);
  }
  return {
    ...totals,
    targetClassCounts: summarizeCounts(totals.targetClassCounts),
    stopReasonCounts: summarizeCounts(totals.stopReasonCounts),
    operandSignatureCounts: summarizeCounts(totals.operandSignatureCounts),
  };
}

function candidateSummary(candidate, profile) {
  return {
    offset: candidate.offset,
    rawEnd: candidate.rawEnd,
    payloadLength: candidate.payloadLength ?? candidate.rawEnd - candidate.offset - 4,
    header: candidate.header,
    paddingLength: candidate.paddingLength,
    paddingZero: candidate.paddingZero,
    linear: {
      instructionCount: profile.linear.instructionCount,
      decodedBytes: profile.linear.decodedBytes,
      invalidCount: profile.linear.invalidCount,
      directCallCount: profile.linear.directCallCount,
      directJumpCount: profile.linear.directJumpCount,
      conditionalJumpCount: profile.linear.conditionalJumpCount,
      directTransferCount: profile.linear.directTransferCount,
      indirectCallCount: profile.linear.indirectCallCount,
      indirectJumpCount: profile.linear.indirectJumpCount,
      targetClassCounts: profile.linear.targetClassCounts,
      operandSignatureCounts: profile.linear.operandSignatureCounts,
    },
    recursive: profile.recursive,
    assumedReturn: profile.assumedReturn,
  };
}

function profileWindows(imagePath, windows, candidateRanges, objdump) {
  return windows.map((window) => {
    const instructions = runObjdump(imagePath, window.start, window.end, objdump);
    const candidate = {
      // The profile's origin is the selected window start.  `objectOffset`
      // remains separate metadata when this is a shifted-start control.
      offset: window.start - 4,
      rawEnd: window.end,
    };
    const profile = profileInstructionStream(instructions, candidate, candidateRanges);
    return {
      ...window,
      payloadLength: window.end - (candidate.offset + 4),
      profile: candidateSummary(candidate, profile),
    };
  });
}

function toolVersion(objdump = DEFAULT_OBJDUMP) {
  return execFileSync(objdump, ['--version'], { encoding: 'utf8' })
    .split('\n', 1)[0]
    .trim();
}

function pllReferenceWindows(pllPath) {
  if (!pllPath) return [];
  const pll = readFileSync(pllPath);
  const table = parseIndexTable(pll, 0x40, {
    expectedCount: 7723,
    label: 'PLL first table for x86 profile controls',
  });
  const objects = parseCompiledObjectTable(pll, table, {
    objectBase: table.offset,
    finalBoundary: 0x2b4b90,
  }).objects;
  const byPrefix = new Map();
  for (const object of objects) {
    const bucket = byPrefix.get(object.prefix) ?? [];
    if (bucket.length < 3) bucket.push(object);
    byPrefix.set(object.prefix, bucket);
  }
  return [...byPrefix.values()]
    .flat()
    .sort((left, right) => left.objectOffset - right.objectOffset)
    .slice(0, 24)
    .map((object) => ({
      label: 'pll-prefix-reference',
      objectOffset: object.objectOffset,
      start: object.objectOffset + 4,
      end: object.rawEnd,
      header: object.header,
      payloadLength: object.encodedWords * 2,
      prefix: object.prefix,
    }));
}

/**
 * Build the full local-only profile for the DXL prologue candidates.
 * `staticIndex` is accepted so exact cross-image anchor metadata can be
 * retained without re-parsing the large PLL during the main candidate pass.
 */
export function buildDxlControlFlowProfile({
  dxlPath,
  staticIndex,
  pllPath = null,
  objdump = DEFAULT_OBJDUMP,
  shiftedCandidateOffsets = null,
  shiftedStarts = [1, 2, 3, 4, 5, 6, 7],
} = {}) {
  if (typeof dxlPath !== 'string' || dxlPath.length === 0) throw new TypeError('dxlPath is required');
  if (!staticIndex || !Array.isArray(staticIndex.dxl?.compiledObjectCandidates?.candidates)) {
    throw new TypeError('staticIndex must contain DXL candidates');
  }
  const dxl = readFileSync(dxlPath);
  const candidates = staticIndex.dxl.compiledObjectCandidates.candidates;
  const candidateRanges = candidates.map((candidate) => ({
    ...candidateRange(candidate),
    objectOffset: candidate.offset,
  }));
  const profiles = candidates.map((candidate) => {
    const instructions = runObjdump(dxlPath, candidate.offset + 4, candidate.rawEnd, objdump);
    return { candidate, profile: profileInstructionStream(instructions, candidate, candidateRanges) };
  });

  const selectedOffsets = shiftedCandidateOffsets ?? candidates
    .filter((candidate) => candidate.payloadLength >= 32)
    .slice(0, 4)
    .map(({ offset }) => offset);
  const shiftedWindows = [];
  for (const objectOffset of selectedOffsets) {
    const candidate = candidates.find((entry) => entry.offset === objectOffset);
    if (!candidate) throw new Error(`shift-control candidate 0x${objectOffset.toString(16)} was not found`);
    for (const shift of shiftedStarts) {
      if (candidate.offset + 4 + shift >= candidate.rawEnd) continue;
      shiftedWindows.push({
        label: 'shifted-candidate-start',
        objectOffset,
        shift,
        start: candidate.offset + 4 + shift,
        end: candidate.rawEnd,
        header: candidate.header,
      });
    }
  }
  const shiftedProfiles = profileWindows(dxlPath, shiftedWindows, candidateRanges, objdump);

  const anchorWindows = (staticIndex.crossReference?.compiledPayloadIdentity?.matches ?? [])
    .filter((match) => match.precedingHeaderMatches && match.dxlCandidateAligned)
    .map((match) => ({
      label: 'exact-pll-dxl-payload-anchor',
      pllObjectOffset: match.pllObjectOffset,
      objectOffset: match.dxlCandidateObjectOffset,
      start: match.dxlPayloadOffset,
      end: match.dxlPayloadOffset + match.payloadLength,
      header: match.dxlPrecedingHeader,
      payloadLength: match.payloadLength,
      payloadSha256: match.payloadSha256,
    }));
  const anchorProfiles = profileWindows(dxlPath, anchorWindows, candidateRanges, objdump);
  const pllWindows = pllReferenceWindows(pllPath);
  const pllProfiles = pllWindows.length
    ? profileWindows(pllPath, pllWindows, [], objdump)
    : [];

  const candidateSummaries = profiles.map(({ candidate, profile }) => candidateSummary(candidate, profile));
  const allLinear = profiles.map(({ profile }) => profile);
  return {
    schemaVersion: 1,
    scope: 'Anonymous bounded x86-like control-flow profile; no DXL/PLL object, entry-point, relocation, symbol, source-module, or Lisp meaning is assigned',
    decoder: {
      command: objdump,
      version: toolVersion(objdump),
      mode: 'objdump -b binary -m i386 -D --insn-width=16',
      caveat: 'Linear and recursive decoding are exploratory byte interpretations; embedded data, tail calls, and Allegro VM conventions can make apparent instructions or transfers non-semantic.',
    },
    image: { name: dxlPath.split(/[\\/]/).at(-1), size: dxl.length, sha256: sha256(dxl) },
    candidateSet: {
      count: candidates.length,
      expectedPrologue: staticIndex.dxl.compiledObjectCandidates.prologue,
      alignment: staticIndex.dxl.compiledObjectCandidates.alignment,
      source: 'static-image-index.json:dxl.compiledObjectCandidates',
    },
    aggregate: aggregateProfiles(allLinear),
    candidates: candidateSummaries,
    controls: {
      shiftedStarts: {
        candidateOffsets: selectedOffsets,
        shifts: shiftedStarts,
        profiles: shiftedProfiles,
      },
      exactPayloadAnchors: {
        profiles: anchorProfiles,
      },
      pllPrefixReferences: {
        sampledWindowCount: pllProfiles.length,
        profiles: pllProfiles,
      },
    },
  };
}

function main(argv) {
  const [dxlPath, staticIndexPath, outputPath, pllPath] = argv;
  if (!dxlPath || !staticIndexPath || !outputPath) {
    throw new Error('Usage: node profile-x86-candidates.mjs DXL STATIC_INDEX OUTPUT_JSON [COMPLETE_PLL]');
  }
  const staticIndex = JSON.parse(readFileSync(staticIndexPath, 'utf8'));
  const profile = buildDxlControlFlowProfile({ dxlPath, staticIndex, pllPath });
  const serialized = `${JSON.stringify(profile, null, 2)}\n`;
  if (outputPath === '-') process.stdout.write(serialized);
  else writeFileSync(outputPath, serialized);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
